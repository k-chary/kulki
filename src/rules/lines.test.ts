import { describe, expect, it } from 'vitest';
import { type Cell, emptyCells } from './board';
import { findAllLines, findLines, lineCells, scoreFor } from './lines';
import { parseBoard } from './testing';

const at = (row: number, col: number): Cell => ({ row, col });

/** Cells from `from` stepping `count` times by (dr, dc), `from` included. */
function run(from: Cell, dr: number, dc: number, count: number): Cell[] {
  return Array.from({ length: count }, (_, i) => at(from.row + dr * i, from.col + dc * i));
}

describe('findLines', () => {
  it('finds a horizontal line', () => {
    const board = parseBoard(`
      .........
      .........
      .........
      .........
      ..rrrrr..
      .........
      .........
      .........
      .........
    `);
    expect(findLines(board, [at(4, 4)])).toEqual([{ color: 'red', cells: run(at(4, 2), 0, 1, 5) }]);
  });

  it('finds a vertical line', () => {
    const board = parseBoard(`
      .........
      ...b.....
      ...b.....
      ...b.....
      ...b.....
      ...b.....
      .........
      .........
      .........
    `);
    expect(findLines(board, [at(5, 3)])).toEqual([
      { color: 'blue', cells: run(at(1, 3), 1, 0, 5) },
    ]);
  });

  it('finds a down-right diagonal line', () => {
    const board = parseBoard(`
      .........
      .g.......
      ..g......
      ...g.....
      ....g....
      .....g...
      .........
      .........
      .........
    `);
    expect(findLines(board, [at(1, 1)])).toEqual([
      { color: 'green', cells: run(at(1, 1), 1, 1, 5) },
    ]);
  });

  it('finds a down-left diagonal line', () => {
    const board = parseBoard(`
      .........
      .........
      .......p.
      ......p..
      .....p...
      ....p....
      ...p.....
      .........
      .........
    `);
    expect(findLines(board, [at(4, 5)])).toEqual([
      { color: 'purple', cells: run(at(2, 7), 1, -1, 5) },
    ]);
  });

  it('finds lines touching the board edges and corners', () => {
    const board = parseBoard(`
      yyyyy...o
      .......o.
      ......o..
      .....o...
      ....o...r
      ........r
      ........r
      ........r
      ...rrrrrr
    `);
    expect(findAllLines(board)).toEqual([
      { color: 'yellow', cells: run(at(0, 0), 0, 1, 5) },
      { color: 'orange', cells: run(at(0, 8), 1, -1, 5) },
      { color: 'red', cells: run(at(4, 8), 1, 0, 5) },
      { color: 'red', cells: run(at(8, 3), 0, 1, 6) },
    ]);
  });

  it('returns runs of 6 and 9 whole', () => {
    const board = parseBoard(`
      bbbbbbbbb
      .........
      .........
      .........
      .........
      .........
      .........
      .........
      .gggggg..
    `);
    expect(findLines(board, [at(0, 8)])).toEqual([
      { color: 'blue', cells: run(at(0, 0), 0, 1, 9) },
    ]);
    expect(findLines(board, [at(8, 3)])).toEqual([
      { color: 'green', cells: run(at(8, 1), 0, 1, 6) },
    ]);
  });

  it('finds a full-length diagonal of 9', () => {
    const board = parseBoard(`
      r........
      .r.......
      ..r......
      ...r.....
      ....r....
      .....r...
      ......r..
      .......r.
      ........r
    `);
    expect(findLines(board, [at(4, 4)])).toEqual([{ color: 'red', cells: run(at(0, 0), 1, 1, 9) }]);
  });

  it('does not clear a run of 4', () => {
    const board = parseBoard(`
      .........
      .rrrr....
      .r.......
      .r.......
      .r.......
      .........
      ....r....
      .....r...
      ......r..
    `);
    expect(findAllLines(board)).toEqual([]);
  });

  it('does not join adjacent balls of different colors', () => {
    const board = parseBoard(`
      rrrrbbbb.
      r........
      r........
      r........
      o........
      .........
      ..y......
      ...g.....
      ....y....
    `);
    expect(findAllLines(board)).toEqual([]);
  });

  it('does not join a run across an empty square', () => {
    const board = parseBoard(`
      rr.rrr...
      .........
      .........
      .........
      .........
      .........
      .........
      .........
      .........
    `);
    expect(findAllLines(board)).toEqual([]);
  });

  it('only looks at lines through the given cells', () => {
    const board = parseBoard(`
      rrrrr....
      .........
      .........
      .........
      .........
      .........
      .........
      .........
      ....bbbbb
    `);
    expect(findLines(board, [at(8, 8)])).toEqual([
      { color: 'blue', cells: run(at(8, 4), 0, 1, 5) },
    ]);
    expect(findLines(board, [at(4, 4)])).toEqual([]);
    expect(findLines(board, [])).toEqual([]);
  });

  it('ignores empty cells and reports a line once however many of its cells are given', () => {
    const board = parseBoard(`
      .........
      .........
      .........
      .........
      ..ooooo..
      .........
      .........
      .........
      .........
    `);
    const line = run(at(4, 2), 0, 1, 5);
    expect(findLines(board, [...line, at(0, 0), ...line])).toEqual([
      { color: 'orange', cells: line },
    ]);
  });

  it('finds crossing lines (X) through their shared ball', () => {
    const board = parseBoard(`
      .........
      .........
      ..y...y..
      ...y.y...
      ....y....
      ...y.y...
      ..y...y..
      .........
      .........
    `);
    expect(findLines(board, [at(4, 4)])).toEqual([
      { color: 'yellow', cells: run(at(2, 2), 1, 1, 5) },
      { color: 'yellow', cells: run(at(2, 6), 1, -1, 5) },
    ]);
  });

  it('finds a plus (+) and a T shape', () => {
    const plus = parseBoard(`
      .........
      .........
      ....g....
      ....g....
      ..ggggg..
      ....g....
      ....g....
      .........
      .........
    `);
    expect(findLines(plus, [at(4, 4)])).toEqual([
      { color: 'green', cells: run(at(2, 4), 1, 0, 5) },
      { color: 'green', cells: run(at(4, 2), 0, 1, 5) },
    ]);
    const t = parseBoard(`
      .........
      .bbbbb...
      ...b.....
      ...b.....
      ...b.....
      ...b.....
      .........
      .........
      .........
    `);
    expect(findLines(t, [at(1, 3)])).toEqual([
      { color: 'blue', cells: run(at(1, 1), 0, 1, 5) },
      { color: 'blue', cells: run(at(1, 3), 1, 0, 5) },
    ]);
  });

  it('finds an L shape through its corner', () => {
    const board = parseBoard(`
      .........
      .........
      .........
      .........
      p........
      p........
      p........
      p........
      ppppp....
    `);
    expect(findLines(board, [at(8, 0)])).toEqual([
      { color: 'purple', cells: run(at(4, 0), 1, 0, 5) },
      { color: 'purple', cells: run(at(8, 0), 0, 1, 5) },
    ]);
  });

  it('finds two separate lines formed at once', () => {
    const withSpawn = parseBoard(`
      .........
      rrrrr....
      .........
      .........
      ........b
      ........b
      ........b
      ........b
      ........b
    `);
    expect(findLines(withSpawn, [at(1, 4), at(4, 8)])).toEqual([
      { color: 'red', cells: run(at(1, 0), 0, 1, 5) },
      { color: 'blue', cells: run(at(4, 8), 1, 0, 5) },
    ]);
  });

  it('finds every line on a crowded board', () => {
    const board = parseBoard(`
      rrrrrrrrr
      rrrrrrrrr
      rrrrrrrrr
      rrrrrrrrr
      rrrrrrrrr
      rrrrrrrrr
      rrrrrrrrr
      rrrrrrrrr
      rrrrrrrrr
    `);
    // 9 rows, 9 columns and the 9 diagonals of length 5 or more in each diagonal direction.
    expect(findAllLines(board)).toHaveLength(9 + 9 + 9 + 9);
    expect(lineCells(findAllLines(board))).toHaveLength(81);
    expect(emptyCells(board)).toEqual([]);
  });
});

describe('lineCells and scoreFor', () => {
  it('counts a ball shared by two crossing 5-lines once: 9 balls, 90 points', () => {
    const board = parseBoard(`
      .........
      .........
      ....g....
      ....g....
      ..ggggg..
      ....g....
      ....g....
      .........
      .........
    `);
    const cells = lineCells(findLines(board, [at(4, 4)]));
    expect(cells).toHaveLength(9);
    expect(cells[0]).toEqual(at(2, 4));
    expect(cells.at(-1)).toEqual(at(6, 4));
    expect(scoreFor(cells)).toBe(90);
  });

  it('gives 10 points per distinct ball with no bonus', () => {
    expect(scoreFor([])).toBe(0);
    expect(scoreFor(run(at(0, 0), 0, 1, 5))).toBe(50);
    expect(scoreFor(run(at(0, 0), 0, 1, 9))).toBe(90);
    expect(scoreFor([at(1, 1), at(1, 1), at(2, 2)])).toBe(20);
  });
});
